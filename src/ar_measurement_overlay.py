    def __init__(self, smoothing_alpha: float = 0.35) -> None:
        """
        Initializes the AR measurement overlay engine.

        Args:
            smoothing_alpha: Exponential smoothing factor [0.0, 1.0] for display
                             label coordinates only (0.35 = 35% current, 65% previous).
        """
        self.smoothing_alpha: float = smoothing_alpha

        # Temporal smoothing cache for visual label positions: key -> (smooth_x, smooth_y)
        self.smoothed_positions: Dict[str, Tuple[float, float]] = {}

        # Visual styling palette (BGR format for OpenCV)
        self.color_line: Tuple[int, int, int] = (0, 215, 255)       # Vibrant Gold / Amber
        self.color_tick: Tuple[int, int, int] = (255, 255, 255)     # Crisp White
        self.color_box_bg: Tuple[int, int, int] = (20, 24, 30)      # Charcoal Dark
        self.color_box_border: Tuple[int, int, int] = (0, 200, 255)  # Gold/Amber border
        self.color_text_title: Tuple[int, int, int] = (200, 230, 255) # Light Ice Blue
        self.color_text_val: Tuple[int, int, int] = (255, 255, 255)  # Crisp White
        self.color_circ_line: Tuple[int, int, int] = (255, 180, 0)   # Vivid Cyan/Blue
        self.color_conf_high: Tuple[int, int, int] = (0, 255, 120)   # Green
        self.color_conf_low: Tuple[int, int, int] = (0, 180, 255)    # Orange/Yellow

    def clamp_text_position(
        self,
        x: int,
        y: int,
        box_width: int,
        box_height: int,
        frame_width: int,
        frame_height: int,
        margin: int = 12,
    ) -> Tuple[int, int]:
        """
        Ensures label bounding boxes remain fully visible within the camera frame bounds.
        """
        clamped_x = max(margin, min(frame_width - box_width - margin, x))
        clamped_y = max(margin, min(frame_height - box_height - margin, y))
        return int(clamped_x), int(clamped_y)

    def _get_smoothed_position(
        self,
        key: str,
        target_x: float,
        target_y: float,
    ) -> Tuple[int, int]:
        """
        Applies lightweight exponential temporal smoothing exclusively to label screen coordinates.
        Formula: smoothed = alpha * current + (1 - alpha) * previous
        """
        if key in self.smoothed_positions:
            prev_x, prev_y = self.smoothed_positions[key]
            # Smooth position
            smooth_x = self.smoothing_alpha * target_x + (1.0 - self.smoothing_alpha) * prev_x
            smooth_y = self.smoothing_alpha * target_y + (1.0 - self.smoothing_alpha) * prev_y
        else:
            smooth_x, smooth_y = target_x, target_y

        self.smoothed_positions[key] = (smooth_x, smooth_y)
        return int(round(smooth_x)), int(round(smooth_y))

    def draw_measurement_line(
        self,
        frame: np.ndarray,
        p1: Tuple[int, int],
        p2: Tuple[int, int],
        tick_length: int = 7,
        line_color: Optional[Tuple[int, int, int]] = None,
        tick_color: Optional[Tuple[int, int, int]] = None,
    ) -> None:
        """
        Draws a CAD-style dimension line between two joint points with perpendicular end-cap ticks:
               ├──────────────┤
        """
        color = line_color or self.color_line
        t_color = tick_color or self.color_tick

        x1, y1 = p1
        x2, y2 = p2

        dx = x2 - x1
        dy = y2 - y1
        length = math.hypot(dx, dy)

        if length < 1.0:
            return

        # Main measurement connecting line
        cv2.line(frame, (x1, y1), (x2, y2), color, 1, cv2.LINE_AA)

        # Perpendicular normal unit vector
        nx = -dy / length
        ny = dx / length

        # Small endpoint dots
        cv2.circle(frame, (x1, y1), 3, color, -1, cv2.LINE_AA)
        cv2.circle(frame, (x2, y2), 3, color, -1, cv2.LINE_AA)

        # Perpendicular tick at P1
        t1_a = (int(round(x1 - nx * tick_length)), int(round(y1 - ny * tick_length)))
        t1_b = (int(round(x1 + nx * tick_length)), int(round(y1 + ny * tick_length)))
        cv2.line(frame, t1_a, t1_b, t_color, 2, cv2.LINE_AA)

        # Perpendicular tick at P2
        t2_a = (int(round(x2 - nx * tick_length)), int(round(y2 - ny * tick_length)))
        t2_b = (int(round(x2 + nx * tick_length)), int(round(y2 + ny * tick_length)))
        cv2.line(frame, t2_a, t2_b, t_color, 2, cv2.LINE_AA)

    def draw_measurement_label(
        self,
        frame: np.ndarray,
        center_x: int,
        center_y: int,
        title: str,
        value_text: str,
        sub_text: Optional[str] = None,
        confidence_dot: Optional[Tuple[int, int, int]] = None,
    ) -> None:
        """
        Renders a compact, high-contrast glassmorphic label badge with anti-aliased text.
        """
        h_frame, w_frame = frame.shape[:2]

        font = cv2.FONT_HERSHEY_SIMPLEX
        font_scale_title = 0.36
        font_scale_val = 0.44
        font_scale_sub = 0.34

        # Compute text bounding sizes
        size_title, _ = cv2.getTextSize(title, font, font_scale_title, 1)
        size_val, _ = cv2.getTextSize(value_text, font, font_scale_val, 1)

        extra_w = 16 if confidence_dot else 0
        box_w = max(size_title[0], size_val[0] + extra_w) + 18
        box_h = 36 if not sub_text else 48

        # Center the box around (center_x, center_y)
        box_x = int(center_x - box_w / 2)
        box_y = int(center_y - box_h / 2)

        # Clamp safely within camera viewport
        box_x, box_y = self.clamp_text_position(box_x, box_y, box_w, box_h, w_frame, h_frame)

        # Semi-transparent background badge using local ROI for maximum performance
        roi = frame[box_y : box_y + box_h, box_x : box_x + box_w]
        if roi.shape[0] > 0 and roi.shape[1] > 0:
            bg_card = np.full_like(roi, self.color_box_bg)
            cv2.addWeighted(bg_card, 0.82, roi, 0.18, 0, roi)


        # Border
        cv2.rectangle(
            frame,
            (box_x, box_y),
            (box_x + box_w, box_y + box_h),
            self.color_box_border,
            1,
            cv2.LINE_AA,
        )

        # Title text (e.g. "Shoulder")
        title_y = box_y + 14
        cv2.putText(
            frame,
            title,
            (box_x + 8, title_y),
            font,
            font_scale_title,
            self.color_text_title,
            1,
            cv2.LINE_AA,
        )

        # Value text (e.g. "34.87 cm")
        val_y = box_y + 30
        cv2.putText(
            frame,
            value_text,
            (box_x + 8, val_y),
            font,
            font_scale_val,
            self.color_text_val,
            1,
            cv2.LINE_AA,
        )

        # Optional confidence indicator dot
        if confidence_dot:
            dot_x = box_x + 8 + size_val[0] + 8
            dot_y = val_y - 4
            cv2.circle(frame, (dot_x, dot_y), 4, confidence_dot, -1, cv2.LINE_AA)

        # Optional sub-text (e.g. "Conf: 92% | Stab: 98%")
        if sub_text:
            sub_y = box_y + 44
            cv2.putText(
                frame,
                sub_text,
                (box_x + 8, sub_y),
                font,
                font_scale_sub,
                (180, 200, 210),
                1,
                cv2.LINE_AA,
            )

    def draw_segment_measurement(
        self,
        frame: np.ndarray,
        p1: ARPoint,
        p2: ARPoint,
        key: str,
        display_name: str,
        value_cm: float,
        torso_center: Tuple[float, float],
        offset_mode: str = "outward",
    ) -> None:
        """
        Draws a segment dimension line and anchored smoothed measurement label.
        """
        if not (p1.valid and p2.valid):
            return

        pt1 = (p1.pixel_x, p1.pixel_y)
        pt2 = (p2.pixel_x, p2.pixel_y)

        # Draw CAD-style dimension line
        self.draw_measurement_line(frame, pt1, pt2)

        # Midpoint of the segment
        mid_x = (p1.pixel_x + p2.pixel_x) * 0.5
        mid_y = (p1.pixel_y + p2.pixel_y) * 0.5

        # Calculate outward projection vector to avoid overlapping the body
        if offset_mode == "top":
            # For shoulders: project upward away from body center
            target_x = mid_x
            target_y = mid_y - 38.0
        else:
            # For arms and legs: project outward away from torso center
            tc_x, tc_y = torso_center
            dir_x = mid_x - tc_x
            dir_y = mid_y - tc_y
            dist = math.hypot(dir_x, dir_y)
            if dist > 1e-3:
                u_x = dir_x / dist
                u_y = dir_y / dist
            else:
                u_x, u_y = 1.0, 0.0

            # Project label outward
            target_x = mid_x + u_x * 42.0
            target_y = mid_y + u_y * 12.0

        # Apply temporal display smoothing
        smooth_x, smooth_y = self._get_smoothed_position(key, target_x, target_y)

        # Format label string
        val_str = f"{value_cm:.2f} cm"

        # Render label badge
        self.draw_measurement_label(
            frame=frame,
            center_x=smooth_x,
            center_y=smooth_y,
            title=display_name,
            value_text=val_str,
        )

    def draw_circumference_measurement(
        self,
        frame: np.ndarray,
        key: str,
        display_name: str,
        value_cm: float,
        anchor_pt: Tuple[int, int],
        span_width: int,
        confidence: float = 0.0,
        stability_pct: float = 0.0,
    ) -> None:
        """
        Draws an AR horizontal span indicator (<──────────────>) and circumference label:
               <──────────────>
                  CHEST
                  82.0 cm
        """
        if value_cm <= 0.0:
            return

        cx, cy = anchor_pt
        half_w = max(25, int(span_width * 0.42))

        x_left = cx - half_w
        x_right = cx + half_w
        y_span = cy

        # Draw horizontal span line
        cv2.line(frame, (x_left, y_span), (x_right, y_span), self.color_circ_line, 1, cv2.LINE_AA)

        # Arrowhead left '<'
        arrow_size = 6
        cv2.line(
            frame,
            (x_left, y_span),
            (x_left + arrow_size, y_span - arrow_size),
            self.color_circ_line,
            2,
            cv2.LINE_AA,
        )
        cv2.line(
            frame,
            (x_left, y_span),
            (x_left + arrow_size, y_span + arrow_size),
            self.color_circ_line,
            2,
            cv2.LINE_AA,
        )

        # Arrowhead right '>'
        cv2.line(
            frame,
            (x_right, y_span),
            (x_right - arrow_size, y_span - arrow_size),
            self.color_circ_line,
            2,
            cv2.LINE_AA,
        )
        cv2.line(
            frame,
            (x_right, y_span),
            (x_right - arrow_size, y_span + arrow_size),
            self.color_circ_line,
            2,
            cv2.LINE_AA,
        )

        # Confidence status color
        conf_dot = self.color_conf_high if confidence >= 0.80 else self.color_conf_low

        # Apply temporal display smoothing to label anchor
        target_label_x = cx
        target_label_y = cy - 26
        smooth_x, smooth_y = self._get_smoothed_position(f"circ_{key}", target_label_x, target_label_y)

        # Subtext with confidence and stability
        sub_str = None
        if confidence > 0.0 or stability_pct > 0.0:
            parts = []
            if confidence > 0.0:
                parts.append(f"Conf: {int(confidence * 100)}%")
            if stability_pct > 0.0:
                parts.append(f"Stab: {int(stability_pct)}%")
            sub_str = " | ".join(parts)

        val_str = f"{value_cm:.1f} cm"

        # Render label badge
        self.draw_measurement_label(
            frame=frame,
            center_x=smooth_x,
            center_y=smooth_y,
            title=display_name.upper(),
            value_text=val_str,
            sub_text=sub_str,
            confidence_dot=conf_dot if confidence > 0.0 else None,
        )

    def draw_all_measurements(
        self,
        frame: np.ndarray,
        mapped_points: Dict[str, ARPoint],
        linear_measurements: Optional[Dict[str, float]],
        circumference_data: Optional[Dict[str, Dict[str, Any]]] = None,
    ) -> np.ndarray:
        """
        Coordinates full rendering of Phase 6.2 AR measurements over the camera image.

        Args:
            frame: OpenCV BGR image frame.
            mapped_points: Dictionary of mapped ARPoint objects from ARCoordinateMapper.
            linear_measurements: Dictionary of segment lengths in cm.
            circumference_data: Dictionary of circumference values, confidence, and stability.

        Returns:
            OpenCV BGR image with AR measurement lines, ticks, and labels rendered.
        """
        if not mapped_points:
            return frame

        # Compute torso center for outward perpendicular vector projection
        ls = mapped_points.get("LEFT_SHOULDER")
        rs = mapped_points.get("RIGHT_SHOULDER")
        lh = mapped_points.get("LEFT_HIP")
        rh = mapped_points.get("RIGHT_HIP")

        if ls and rs and ls.valid and rs.valid:
            sh_mid_x = (ls.pixel_x + rs.pixel_x) * 0.5
            sh_mid_y = (ls.pixel_y + rs.pixel_y) * 0.5
            shoulder_span = math.hypot(rs.pixel_x - ls.pixel_x, rs.pixel_y - ls.pixel_y)
        else:
            sh_mid_x, sh_mid_y = frame.shape[1] * 0.5, frame.shape[0] * 0.35
            shoulder_span = 120.0

        if lh and rh and lh.valid and rh.valid:
            hip_mid_x = (lh.pixel_x + rh.pixel_x) * 0.5
            hip_mid_y = (lh.pixel_y + rh.pixel_y) * 0.5
            hip_span = math.hypot(rh.pixel_x - lh.pixel_x, rh.pixel_y - lh.pixel_y)
        else:
            hip_mid_x, hip_mid_y = sh_mid_x, sh_mid_y + 160.0
            hip_span = shoulder_span * 0.85

        torso_cx = (sh_mid_x + hip_mid_x) * 0.5
        torso_cy = (sh_mid_y + hip_mid_y) * 0.5
        torso_center = (torso_cx, torso_cy)

        # -------------------------------------------------------------
        # 1. SEGMENT MEASUREMENT OVERLAYS
        # -------------------------------------------------------------
        if linear_measurements:
            for cfg in self.SEGMENT_CONFIGS:
                key = cfg["key"]
                val = linear_measurements.get(key)
                if val is None or val <= 0.0:
                    continue

                p1 = mapped_points.get(cfg["pt1"])
                p2 = mapped_points.get(cfg["pt2"])

                if p1 and p2 and p1.valid and p2.valid:
                    self.draw_segment_measurement(
                        frame=frame,
                        p1=p1,
                        p2=p2,
                        key=key,
                        display_name=cfg["display_name"],
                        value_cm=float(val),
                        torso_center=torso_center,
                        offset_mode=cfg["offset_mode"],
                    )

        # -------------------------------------------------------------
        # 2. CIRCUMFERENCE MEASUREMENT OVERLAYS (Chest, Waist, Hip)
        # -------------------------------------------------------------
        if circumference_data:
            # Chest: Anchored ~28% down torso
            chest_info = circumference_data.get("chest")
            if chest_info and chest_info.get("value_cm", 0.0) > 0.0:
                if ls and rs and ls.valid and rs.valid:
                    chest_x = int(sh_mid_x + (hip_mid_x - sh_mid_x) * 0.28)
                    chest_y = int(sh_mid_y + (hip_mid_y - sh_mid_y) * 0.28)
                    self.draw_circumference_measurement(
                        frame=frame,
                        key="chest",
                        display_name="Chest",
                        value_cm=float(chest_info["value_cm"]),
                        anchor_pt=(chest_x, chest_y),
                        span_width=int(shoulder_span * 0.82),
                        confidence=float(chest_info.get("confidence", 0.0)),
                        stability_pct=float(chest_info.get("stability_pct", 0.0)),
                    )

            # Waist: Anchored ~55% down torso
            waist_info = circumference_data.get("waist")
            if waist_info and waist_info.get("value_cm", 0.0) > 0.0:
                if ls and rs and lh and rh and ls.valid and rs.valid and lh.valid and rh.valid:
                    waist_x = int(sh_mid_x + (hip_mid_x - sh_mid_x) * 0.55)
                    waist_y = int(sh_mid_y + (hip_mid_y - sh_mid_y) * 0.55)
                    waist_span = int(shoulder_span * 0.68)
                    self.draw_circumference_measurement(
                        frame=frame,
                        key="waist",
                        display_name="Waist",
                        value_cm=float(waist_info["value_cm"]),
                        anchor_pt=(waist_x, waist_y),
                        span_width=waist_span,
                        confidence=float(waist_info.get("confidence", 0.0)),
                        stability_pct=float(waist_info.get("stability_pct", 0.0)),
                    )

            # Hip: Anchored at hips
            hip_info = circumference_data.get("hip")
            if hip_info and hip_info.get("value_cm", 0.0) > 0.0:
                if lh and rh and lh.valid and rh.valid:
                    hip_x = int(hip_mid_x)
                    hip_y = int(hip_mid_y)
                    self.draw_circumference_measurement(
                        frame=frame,
                        key="hip",
                        display_name="Hip",
                        value_cm=float(hip_info["value_cm"]),
                        anchor_pt=(hip_x, hip_y),
                        span_width=int(hip_span),
                        confidence=float(hip_info.get("confidence", 0.0)),
                        stability_pct=float(hip_info.get("stability_pct", 0.0)),
                    )

        return frame
